"""
base_vlm.py

Abstract base interface for all Vision-Language Models used by the
KGFLM Traffic Annotation Pipeline.

Every Scene Understanding model must inherit from BaseVLM. The pipeline
interacts exclusively with this interface, allowing different local VLMs
to be used interchangeably without modifying any downstream pipeline
components.

The base interface defines the common lifecycle expected from every
implementation.

Pipeline

Configuration
      │
      ▼
Load Model
      │
      ▼
Run Inference
      │
      ▼
Unload Model

Responsibilities

• Define a common interface for every Vision-Language Model.
• Standardize model loading and unloading.
• Standardize inference across all backends.
• Provide common utility properties used throughout the pipeline.
• Enable interchangeable Scene Understanding backends.

Typical lifecycle

    model = SmolVLM(config)

    model.load()

    response = model.infer(
        image_path=image_path,
        prompt=prompt,
    )

    model.unload()
"""
# ============================================================================
# Imports
# ============================================================================
from __future__ import annotations

from custom_logger import CustomLogger

from abc import ABC, abstractmethod
from pathlib import Path
from typing import Any
logger = CustomLogger(__name__)


class BaseVLM(ABC):
    """
    Abstract base class for every Scene Understanding Vision-Language Model.

    Every local or remote VLM implementation must inherit from this class.

    The annotation pipeline communicates exclusively through this interface,
    making all supported models interchangeable regardless of their internal
    implementation.

    Concrete subclasses are responsible for implementing:

    • Model loading
    • Resource cleanup
    • Scene understanding inference

    This class intentionally contains no framework-specific logic.
    """
    # -------------------------------------------------------------------------
    # Initialization
    # -------------------------------------------------------------------------

    def __init__(self, config: Any) -> None:
        """
        Initialize the common model state.

        Every derived model maintains the same internal attributes regardless of
        its implementation framework. Concrete subclasses populate these
        attributes during the loading stage.
        """

        self.config = config

        self.model = None
        self.processor = None
        self.device = None

        self.loaded = False
        logger.debug(
            "Initialized BaseVLM interface."
        )
    # -------------------------------------------------------------------------
    # Model Lifecycle
    # -------------------------------------------------------------------------

    @abstractmethod
    def load(self) -> None:
        """
        Load model resources into memory.

        Concrete implementations should initialize every resource required for
        inference, including model weights, processors, tokenizers, and any
        backend-specific components.

        This method should be safe to call multiple times without loading the
        model repeatedly.
        """
        raise NotImplementedError

    @abstractmethod
    def unload(self) -> None:
        """
        Release model resources.

        Concrete implementations should free every allocated resource,
        including GPU memory whenever applicable.

        Calling this method multiple times should be safe.
        """
        raise NotImplementedError

    # ------------------------------------------------------------------
    # Inference
    # ------------------------------------------------------------------

    @abstractmethod
    def infer(
        self,
        image_path: Path,
        prompt: str,
    ) -> str:
        """
        Perform Scene Understanding on a single image.

        Parameters
        ----------
        image_path
            Path to the input image.

        prompt
            Prompt describing the required Scene Understanding task.

        Returns
        -------
        str
            Raw text generated by the Vision-Language Model.

        Notes
        -----
        The returned response is intentionally left unprocessed.

        Parsing, validation, and caching are handled by
        SceneUnderstandingEngine.
        """
        raise NotImplementedError

    # ------------------------------------------------------------------
    # Utilities
    # ------------------------------------------------------------------

    @property
    def is_loaded(self) -> bool:
        """
        Whether the model has been successfully loaded.

        Returns
        -------
        bool
            True if the model is currently available for inference.
        """

        return self.loaded

    @property
    def model_name(self) -> str:
        """
         Return a human-readable model identifier.

         Concrete implementations typically expose the Hugging Face model ID.
         If unavailable, the implementation class name is returned instead.

         Returns
         -------
         str
             Human-readable model identifier.
         """

        return getattr(self, "model_id", self.__class__.__name__)

    def __repr__(self) -> str:
        """
        Return a concise string representation of the model state.
        """

        return (
            f"{self.model_name}("
            f"loaded={self.loaded}, "
            f"device={self.device}"
            f")"
        )
